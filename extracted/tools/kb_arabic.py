"""Arabic knowledge for Nuwaa: (1) word meanings from data/lexicon_ar.psv, (2) grammar and spelling rules, (3) Gulf dialect -> Fusha.
Add a word by adding ONE line to data/lexicon_ar.psv:  word|meaning|synonyms|antonyms|example   (use - when there is none).
Honest limit: this is a growing hand-written dictionary, not the whole Arabic language."""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
LEX = ROOT / "data" / "lexicon_ar.psv"

def read_lexicon():
    rows = []
    for n, l in enumerate(LEX.read_text(encoding="utf-8").splitlines(), 1):
        if not l.strip(): continue
        p = [x.strip() for x in l.split("|")]
        if len(p) != 5 or not all(p): raise SystemExit(f"lexicon_ar.psv line {n}: need 5 non-empty fields (use - for none): {l!r}")
        rows.append(p)
    words = [r[0] for r in rows]
    dup = {w for w in words if words.count(w) > 1}
    if dup: raise SystemExit(f"lexicon_ar.psv duplicate words: {sorted(dup)}")
    # a word must be findable: its search tokens must exist, must not be the generic word «كلمة», and must not equal another word's tokens
    # (e.g. الخطأ and مشكلة are the same token for the search engine; يعلّم and يعلم differ only by a diacritic)
    import sys
    sys.path.insert(0, str(ROOT))
    from nuwaa.memory.kb import tokens
    seen = {}
    for w in words:
        t = frozenset(tokens(w))
        if not t or t == frozenset(tokens("كلمة")): raise SystemExit(f"lexicon_ar.psv: «{w}» cannot be searched (it is a stop word or the word «كلمة»); choose another word")
        if t in seen: raise SystemExit(f"lexicon_ar.psv: «{w}» and «{seen[t]}» are the same word for the search engine; keep one")
        seen[t] = w
    return rows

def lexicon_answer(w, mean, syn, ant, ex):
    t = f"«{w}»: {mean}."
    if syn != "-": t += f"\nمرادفها: {syn}."
    if ant != "-": t += f"\nضدها: {ant}."
    return t + f"\nمثال: {ex}"

def lexicon_questions(w, syn, ant):
    qs = [f"ما معنى كلمة {w}", f"ماذا تعني كلمة {w}", f"معنى {w}"]
    if syn != "-": qs.append(f"ما مرادف {w}")
    if ant != "-": qs += [f"ما ضد {w}", f"ما عكس كلمة {w}"]
    return qs

